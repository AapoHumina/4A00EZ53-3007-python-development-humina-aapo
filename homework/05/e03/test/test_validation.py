import unittest

from util.validation import is_date, is_email, is_personal_id

class TestValidation(unittest.TestCase):
    def test_is_date(self):
        self.assertTrue(is_date("2022-10-10"))
        self.assertTrue(is_date("0000-01-01"))
        self.assertTrue(is_date("0000-12-31"))
        self.assertTrue(is_date("9999-12-31"))
        self.assertTrue(is_date("9999-01-01"))
        self.assertTrue(is_date("2000-01-01"))
        self.assertTrue(is_date("1993-10-10"))
        self.assertTrue(is_date("1111-10-30"))
        self.assertTrue(is_date("4500-12-24"))
        self.assertFalse(is_date("-2022-33-33"))
        self.assertFalse(is_date("2022-03-03-"))
        self.assertFalse(is_date("20-22-33-33"))
        self.assertFalse(is_date("2022-3-3-3-3"))
        self.assertFalse(is_date("2022-3333"))
        self.assertFalse(is_date("rghfghfghfh"))
        self.assertFalse(is_date("fghd-df-fg"))
        self.assertFalse(is_date("2022-00-00"))
        self.assertFalse(is_date({"2342", "3453", "34534"}))
        self.assertFalse(is_date(5436576457657))
        self.assertFalse(is_date(3453456.4567756))
        self.assertFalse(is_date(2335-12-12))
        self.assertFalse(is_date("kkkk-rr-ww"))
        self.assertFalse(is_date("DDDD-DD-DD"))
        self.assertFalse(is_date("0000-00-00"))
        self.assertFalse(is_date(("1234","12","12")))
        #self.assertRaises(Exception, is_date, 23423)
        #self.assertRaises(Exception, is_date, {"2342", "3453", "34534"})
        #self.assertRaises(Exception, is_date, 234.234)
        #self.assertRaises(Exception, is_date, 36457546865746845746857486548675)
        #self.assertRaises(Exception, is_date, "5656567567")

    def test_is_email(self):
        self.assertTrue(is_email("jussi.pohjolainen@tuni.fi"))
        self.assertTrue(is_email("abc-d@mail.com"))
        self.assertTrue(is_email("abc.def@mail.com"))
        self.assertTrue(is_email("abc@mail.com"))
        self.assertTrue(is_email("abc_def@mail.com"))
        self.assertTrue(is_email("abc.def@mail.cc"))
        self.assertTrue(is_email("abc.def@mail-archive.com"))
        self.assertTrue(is_email("abc.def@mail.org"))
        self.assertTrue(is_email("abc.def@mail.com"))
        self.assertTrue(is_email("heikki.h.humina@gmail.com"))
        self.assertTrue(is_email("jussi-jassu.pohjolainen-pohjalainen@tuni.fi"))
        self.assertFalse(is_email("abc-@mail.com"))
        self.assertFalse(is_email("abc..def@mail.com"))
        self.assertFalse(is_email(".abc@mail.com"))
        self.assertFalse(is_email("abc#def@mail.com"))
        self.assertFalse(is_email("abc.def@mail.c"))
        self.assertFalse(is_email("abc.def@mail#archive.com"))
        self.assertFalse(is_email("abc.def@mail"))
        self.assertFalse(is_email("abc.def@mail..com"))
        self.assertFalse(is_email("fgdfhdfhgdfhdfgdfg"))
        self.assertFalse(is_email("4534458756798634"))
        self.assertFalse(is_email("345345354@@@@23423443"))
        self.assertFalse(is_email("34234234.23422@@213123.12"))
        self.assertFalse(is_email("jussi.pohjolainen@tuni.i"))
        self.assertFalse(is_email("jussi.pohjolainen@tuni"))
        self.assertFalse(is_email("jussi.pohjolainen@tuni.dfghdfg.dfgdfg.f"))
        self.assertFalse(is_email(3456357458464567456))
        self.assertFalse(is_email({"dfsdfsdf", "dfgdfgdfg", "@"}))
        self.assertFalse(is_email(34643537.345))
        self.assertFalse(is_email("jussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussi@jussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussijussi.fi"))

    def test_is_personal_id(self):
        self.assertTrue(is_personal_id("131052-308T"))
        self.assertTrue(is_personal_id("060388-8768"))
        self.assertTrue(is_personal_id("170688-037P"))
        self.assertTrue(is_personal_id("170588-893H"))
        self.assertTrue(is_personal_id("050988-737Y"))
        self.assertTrue(is_personal_id("050888-576Y"))
        self.assertTrue(is_personal_id("090488-6601"))
        self.assertTrue(is_personal_id("060988-1600"))
        self.assertTrue(is_personal_id("241189-856X"))
        self.assertTrue(is_personal_id("180789-417N"))
        self.assertTrue(is_personal_id("090289-657K"))
        self.assertFalse(is_personal_id("jussi.pohjolainen@tuni.i"))
        self.assertFalse(is_personal_id("56437546rudfu"))
        self.assertFalse(is_personal_id("fhdsfghgsfdghfdghfgh"))
        self.assertFalse(is_personal_id("HAHAHA-HEH4"))
        self.assertFalse(is_personal_id("345678-2340"))
        self.assertFalse(is_personal_id("310678-234Q"))
        self.assertFalse(is_personal_id("311678-234q"))
        self.assertFalse(is_personal_id("311178-234Z"))
        self.assertFalse(is_personal_id("111111-1110"))
        self.assertFalse(is_personal_id("311278-234S"))
        self.assertFalse(is_personal_id("311278-234W"))
        self.assertFalse(is_personal_id("131052F308T"))
        self.assertFalse(is_personal_id("131052B308T"))
